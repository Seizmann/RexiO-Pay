/** Structural shape of the dictionary with plain string leaves. */
type DeepStringify<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends readonly (infer U)[]
      ? U extends string
        ? string[]
        : DeepStringify<U>[]
      : DeepStringify<T[K]>;
};

